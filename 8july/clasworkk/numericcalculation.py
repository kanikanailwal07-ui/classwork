def calculate_sum(num1,num2):
    return num1 + num2
#-----------------------------------
def calculate_difference(num1,num2):
    return num1 - num2
#-----------------------------------
def calculate_multiplication(num1,num2):
    return num1 * num2
#-----------------------------------
def calculate_division(num1,num2):
    return num1 / num2
#-----------------------------------
def calculate_remainder(num1,num2):
    return num1 % num2

