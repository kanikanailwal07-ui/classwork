#function to calculate the area  of a triangle
def calculate_area_of_triangle(base, height):
    return 0.5 * base * height

#function to calculate the perimeter of a triangle
def calculate_perimeter_of_triangle(side1, side2, side3):
    return side1 + side2 + side3

#function to calculate the area of a circle
def calculate_area_of_circle(radius):
    return 3.14159 * radius * radius

#function to calculate the circumference of a circle
def calculate_circumference_of_circle(radius):
    return 2 * 3.14159 * radius

#function to calculate the area of square
def calculate_area_of_square(side):
    return side * side

#function to calculate the perimeter of square
def calculate_perimeter_of_square(side):
    return 4 * side

#function to calculate the area of rectangle
def calculate_area_of_rectangle(length, width):
    return length * width

#function to calculate the perimeter of rectangle
def calculate_perimeter_of_rectangle(length, width):
    return 2 * (length + width)

